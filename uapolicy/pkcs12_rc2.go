// rc2Key is the expanded key K[0..63] of RFC 2268 §2.
type rc2Key [64]uint16

// newRC2Key expands a key of 1 to 128 bytes with an effective key length of
// t1 bits (RFC 2268 §2).
func newRC2Key(key []byte, t1 int) (*rc2Key, error) {
	if len(key) < 1 || len(key) > 128 || t1 < 1 || t1 > 1024 {
		return nil, fmt.Errorf("%w: invalid RC2 key", errors.ErrInvalidPrivateKey)
	}
	var l [128]byte
	t := len(key)
	copy(l[:], key)
	for i := t; i < 128; i++ {
		l[i] = rc2PITable[l[i-1]+l[i-t]]
	}
	t8 := (t1 + 7) / 8
	tm := byte(255 % (int(1) << (8 + t1 - 8*t8))) // 255 MOD 2^(8+T1-8*T8)
	l[128-t8] = rc2PITable[l[128-t8]&tm]
	for i := 127 - t8; i >= 0; i-- {
		l[i] = rc2PITable[l[i+1]^l[i+t8]]
	}
	var k rc2Key
	for i := range k {
		k[i] = uint16(l[2*i]) | uint16(l[2*i+1])<<8
	}
	return &k, nil
}

// decryptBlock decrypts one 8 byte block (RFC 2268 §4): five reverse mixing
// rounds, a reverse mashing round, six mixing rounds, a mashing round and
// five mixing rounds.
func (k *rc2Key) decryptBlock(dst, src []byte) {
	r0 := binary.LittleEndian.Uint16(src[0:])
	r1 := binary.LittleEndian.Uint16(src[2:])
	r2 := binary.LittleEndian.Uint16(src[4:])
	r3 := binary.LittleEndian.Uint16(src[6:])
	j := 63
	mix := func() {
		r3 = bits.RotateLeft16(r3, -5) - k[j] - (r2 & r1) - (^r2 & r0)
		r2 = bits.RotateLeft16(r2, -3) - k[j-1] - (r1 & r0) - (^r1 & r3)
		r1 = bits.RotateLeft16(r1, -2) - k[j-2] - (r0 & r3) - (^r0 & r2)
		r0 = bits.RotateLeft16(r0, -1) - k[j-3] - (r3 & r2) - (^r3 & r1)
		j -= 4
	}
	mash := func() {
		r3 -= k[r2&63]
		r2 -= k[r1&63]
		r1 -= k[r0&63]
		r0 -= k[r3&63]
	}
	for range 5 {
		mix()
	}
	mash()
	for range 6 {
		mix()
	}
	mash()
	for range 5 {
		mix()
	}
	binary.LittleEndian.PutUint16(dst[0:], r0)
	binary.LittleEndian.PutUint16(dst[2:], r1)
	binary.LittleEndian.PutUint16(dst[4:], r2)
	binary.LittleEndian.PutUint16(dst[6:], r3)
}

// rc2DecryptCBC decrypts data in CBC mode; len(data) is a multiple of the
// block size and len(iv) is the block size.
func rc2DecryptCBC(k *rc2Key, iv, data []byte) []byte {
	out := make([]byte, len(data))
	prev := iv
	for i := 0; i+rc2BlockSize <= len(data); i += rc2BlockSize {
		block := data[i : i+rc2BlockSize]
		k.decryptBlock(out[i:i+rc2BlockSize], block)
		for n := range rc2BlockSize {
			out[i+n] ^= prev[n]
		}
		prev = block
	}
	return out
}
