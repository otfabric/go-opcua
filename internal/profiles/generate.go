// The inputs and outputs, relative to the module root.
const (
	SourcePath    = "internal/profiles/testdata/ProfileSet_UACore_1.05.source.json"
	InventoryPath = "internal/profiles/inventory.json"
	ReportPath    = "docs/profiles.md"
	ServerGenPath = "server/server_profiles_gen.go"
)

// Source is the provenance of the pinned profile set.
type Source struct {
	// File is the profile set, relative to the directory of the source.
	File          string `json:"file"`
	URL           string `json:"url"`
	Page          string `json:"page"`
	ProfileGroup  string `json:"profileGroup"`
	ReleaseStatus string `json:"releaseStatus"`
	Retrieved     string `json:"retrieved"`
	// ServedAs is the file name the database gave the download.
	ServedAs string `json:"servedAs"`
	SHA256   string `json:"sha256"`
}

// Generate reads the pinned profile set, its source and the inventory of
// the module at root, checks the evidence and returns the files to write,
// by path relative to root: docs/profiles.md and
// server/server_profiles_gen.go.
func Generate(root string) (map[string][]byte, error) {
	srcData, err := os.ReadFile(filepath.Join(root, SourcePath))
	if err != nil {
		return nil, fmt.Errorf("profiles: %w", err)
	}
	var src Source
	if err := json.Unmarshal(srcData, &src); err != nil {
		return nil, fmt.Errorf("profiles: %s: %w", SourcePath, err)
	}
	setPath := path.Join(path.Dir(SourcePath), src.File)
	set, err := os.ReadFile(filepath.Join(root, setPath))
	if err != nil {
		return nil, fmt.Errorf("profiles: %w", err)
	}
	if sum := sha256.Sum256(set); hex.EncodeToString(sum[:]) != src.SHA256 {
		return nil, fmt.Errorf("profiles: %s: SHA-256 %x, the source pins %s", setPath, sum, src.SHA256)
	}
	ps, err := ParseProfileSet(set)
	if err != nil {
		return nil, err
	}
	if ps.Group != src.ProfileGroup {
		return nil, fmt.Errorf("profiles: %s is profile group %q, the source says %q", setPath, ps.Group, src.ProfileGroup)
	}
	invData, err := os.ReadFile(filepath.Join(root, InventoryPath))
	if err != nil {
		return nil, fmt.Errorf("profiles: %w", err)
	}
	inv, err := ParseInventory(invData)
	if err != nil {
		return nil, err
	}
	rep, err := Evaluate(ps, inv)
	if err != nil {
		return nil, err
	}
	ledger, err := ReadLedger(filepath.Join(root, LedgerPath))
	if err != nil {
		return nil, err
	}
	if err := CheckEvidence(root, inv, ledger); err != nil {
		return nil, err
	}
	rep.Source = src
	return map[string][]byte{
		ReportPath:    Markdown(rep, setPath, ledger.InteropVersion),
		ServerGenPath: ServerGo(rep),
	}, nil
}

// ServerGo returns server/server_profiles_gen.go: the claimed server
// Profiles, the default ServerProfileArray.
func ServerGo(rep *Report) []byte {
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: MIT\n\n")
	b.WriteString("// Code generated by internal/cmd/profiles. DO NOT EDIT.\n\n")
	b.WriteString("package server\n\n")
	b.WriteString("// evidencedServerProfiles are the Profiles of OPC 10000-7 the server lists\n")
	b.WriteString("// in its ServerProfileArray without WithServerProfiles: those whose\n")
	b.WriteString("// mandatory ConformanceUnits, and those of the Profiles they include, are\n")
	b.WriteString("// all evidenced in internal/profiles/inventory.json (docs/profiles.md).\n")
	uris := rep.ServerProfiles()
	if len(uris) == 0 {
		b.WriteString("// No target Profile is yet.\n")
		b.WriteString("var evidencedServerProfiles = []string{}\n")
		return b.Bytes()
	}
	b.WriteString("var evidencedServerProfiles = []string{\n")
	for _, u := range uris {
		fmt.Fprintf(&b, "\t%q,\n", u)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// Markdown returns docs/profiles.md.
func Markdown(rep *Report, setPath, interopVersion string) []byte {
	var b bytes.Buffer
	src := rep.Source
	b.WriteString("# Profiles and conformance units\n\n")
	b.WriteString("<!-- Code generated by internal/cmd/profiles. DO NOT EDIT. -->\n\n")
	b.WriteString("The Profiles of OPC 10000-7 this library targets, with the evidence in this\n")
	b.WriteString("repository for each of their ConformanceUnits. The server lists a Profile in\n")
	b.WriteString("its ServerProfileArray (OPC 10000-5 §6.3.2) only when every mandatory\n")
	b.WriteString("ConformanceUnit of it and of the Profiles it includes is evidenced;\n")
	b.WriteString("`server.WithServerProfiles` replaces the computed list. Nothing here is\n")
	b.WriteString("certified by the OPC Foundation.\n\n")
	fmt.Fprintf(&b, "- Source: the %s Profiles of profile group %s of the\n", src.ReleaseStatus, src.ProfileGroup)
	fmt.Fprintf(&b, "  [OPC Foundation profile database](%s), exported on %s from\n", src.Page, src.Retrieved)
	fmt.Fprintf(&b, "  `%s` (served as\n", src.URL)
	fmt.Fprintf(&b, "  `%s`) and pinned in\n", src.ServedAs)
	fmt.Fprintf(&b, "  `%s`, SHA-256\n", setPath)
	fmt.Fprintf(&b, "  `%s`.\n", src.SHA256)
	fmt.Fprintf(&b, "- Evidence: `%s`. Tests are `dir:TestName`, dir relative\n", InventoryPath)
	b.WriteString("  to the module root; ledger rows are `capability|direction` rows of\n")
	fmt.Fprintf(&b, "  `%s` verified against opcua-interop %s (INTEROP.md).\n", LedgerPath, interopVersion)
	b.WriteString("- Status: **evidenced**, the library does what the unit requires and the\n")
	b.WriteString("  tests assert it; **partial**, a part is implemented or tested, the note\n")
	b.WriteString("  says what is missing; **missing**, not implemented or not tested.\n")
	b.WriteString("- `make gen` writes this file and `server/server_profiles_gen.go`, and\n")
	b.WriteString("  `make check-gen` fails on drift. `go test ./internal/profiles` fails when a\n")
	b.WriteString("  test, ledger row or document of the inventory does not exist, or a\n")
	b.WriteString("  ConformanceUnit of a target has no entry.\n\n")

	b.WriteString("## Summary\n\n")
	b.WriteString("| Profile | Role | Mandatory evidenced / partial / missing | Optional evidenced / partial / missing | Claimed |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for i := range rep.Targets {
		t := &rep.Targets[i]
		fmt.Fprintf(&b, "| %s | %s | %d / %d / %d | %d / %d / %d | %s |\n", t.Profile.Name, t.Role,
			t.Count(false, StatusEvidenced), t.Count(false, StatusPartial), t.Count(false, StatusMissing),
			t.Count(true, StatusEvidenced), t.Count(true, StatusPartial), t.Count(true, StatusMissing),
			yesNo(t.Claimed))
	}
	b.WriteString("\n")
	if uris := rep.ServerProfiles(); len(uris) > 0 {
		fmt.Fprintf(&b, "The default ServerProfileArray is `%s`.\n", strings.Join(uris, "`, `"))
	} else {
		b.WriteString("No server Profile is evidenced: the default ServerProfileArray is empty.\n")
	}

	for i := range rep.Targets {
		t := &rep.Targets[i]
		fmt.Fprintf(&b, "\n## %s\n\n", t.Profile.Name)
		fmt.Fprintf(&b, "URI `%s`, role %s. It includes:\n\n", t.Profile.URI, t.Role)
		for _, p := range t.Included {
			fmt.Fprintf(&b, "- %s, `%s`\n", p.Name, p.URI)
		}
		b.WriteString("\n")
		if t.Claimed {
			b.WriteString("Every mandatory ConformanceUnit is evidenced.\n\n")
		} else {
			b.WriteString("Mandatory ConformanceUnits not evidenced:\n\n")
			for _, r := range t.Rows {
				if !r.Optional && r.Status != StatusEvidenced {
					fmt.Fprintf(&b, "- %s (%s): %s\n", r.Unit.Name, r.Status, r.Note)
				}
			}
			b.WriteString("\n")
		}
		b.WriteString("| Conformance Unit | Required | Status | Evidence | Note |\n")
		b.WriteString("|---|---|---|---|---|\n")
		for _, r := range t.Rows {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", cell(r.Unit.Name), required(r.Optional), r.Status, evidence(r.Entry), cell(r.Note))
		}
	}
	return b.Bytes()
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

func required(optional bool) string {
	if optional {
		return "optional"
	}
	return "mandatory"
}

func evidence(e Entry) string {
	var parts []string
	for _, s := range e.Tests {
		parts = append(parts, "`"+s+"`")
	}
	for _, s := range e.Ledger {
		parts = append(parts, "ledger `"+s+"`")
	}
	for _, s := range e.Docs {
		parts = append(parts, "`"+s+"`")
	}
	return cell(strings.Join(parts, "<br>"))
}

// cell escapes the pipes of a table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
