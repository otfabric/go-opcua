package main

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestRun(t *testing.T) {
	root := t.TempDir()
	write := func(rel, content string) {
		p := filepath.Join(root, rel)
		require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
		require.NoError(t, os.WriteFile(p, []byte(content), 0o644))
	}
	write("a/a.go", "package a\n")
	write("a/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage a\n")
	write("b/b.go", "// Package b.\npackage b\n")

	profile := filepath.Join(root, "cover.out")
	// a: 9 of 10 statements covered (the generated block does not count);
	// b: 1 of 2; each block appears twice (two test binaries).
	require.NoError(t, os.WriteFile(profile, []byte(`mode: atomic
m/a/a.go:1.1,2.1 9 1
m/a/a.go:3.1,4.1 1 0
m/a/gen.go:1.1,2.1 100 0
m/b/b.go:1.1,2.1 1 0
m/b/b.go:3.1,4.1 1 0
m/a/a.go:1.1,2.1 9 0
m/b/b.go:1.1,2.1 1 3
`), 0o644))

	var out bytes.Buffer
	err := run(&out, profile, "m", root, 90)
	require.ErrorContains(t, err, "1 package(s) below 90%: m/b (50.0%)")
	require.Contains(t, out.String(), "ok     90.0%      10 statements  m/a")
	require.Contains(t, out.String(), "FAIL   50.0%       2 statements  m/b")
	require.Contains(t, out.String(), "total 83.3% of 12 statements")

	out.Reset()
	require.NoError(t, run(&out, profile, "m", root, 50))

	require.NoError(t, os.WriteFile(profile, []byte("mode: atomic\nnonsense\n"), 0o644))
	require.ErrorContains(t, run(&out, profile, "m", root, 90), "malformed")
	require.Error(t, run(&out, filepath.Join(root, "missing.out"), "m", root, 90))
}
