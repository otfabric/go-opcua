package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

const header = "// SPDX-License-Identifier: MIT\n\n// Code generated by cmd/methods from %s. DO NOT EDIT.\n\n"

type emitter struct {
	buf bytes.Buffer
}

func (e *emitter) p(format string, args ...any) {
	fmt.Fprintf(&e.buf, format, args...)
	e.buf.WriteByte('\n')
}

func (e *emitter) comment(indent, s string) {
	for _, l := range strings.Split(strings.TrimSpace(s), "\n") {
		e.p("%s// %s", indent, strings.TrimRight(l, " "))
	}
}

// emit returns the source of a family.
func emit(f family, types []*objectType) ([]byte, error) {
	e := &emitter{}
	fmt.Fprintf(&e.buf, header, f.NodeSet)
	e.p("package %s", f.Package)
	e.p("")
	e.p("import (")
	e.p(`"context"`)
	if usesTime(types) {
		e.p(`"time"`)
	}
	e.p("")
	e.p(`"github.com/otfabric/go-opcua/ua"`)
	e.p(")")
	for _, t := range types {
		for _, m := range t.methods {
			e.method(f, t, m)
		}
	}
	out, err := format.Source(e.buf.Bytes())
	if err != nil {
		return e.buf.Bytes(), fmt.Errorf("gofmt: %w", err)
	}
	return out, nil
}

func usesTime(types []*objectType) bool {
	for _, t := range types {
		for _, m := range t.methods {
			for _, a := range append(append([]*arg{}, m.in...), m.out...) {
				if strings.Contains(a.goType(), "time.") {
					return true
				}
			}
		}
	}
	return false
}

// goType is the Go type of the field of an argument.
func (a *arg) goType() string {
	switch {
	case a.structure != "" && a.valueRank == 1:
		return "[]*" + a.structure
	case a.structure != "":
		return "*" + a.structure
	case a.valueRank == 1:
		return "[]" + a.kind.array
	}
	return a.kind.goType
}

// getter returns the call that reads argument i into the field.
func (a *arg) getter(desc string, output bool, i int) string {
	switch {
	case a.structure != "" && a.valueRank == 1:
		return fmt.Sprintf("structures[%s](%s, %v, args, %d)", a.structure, desc, output, i)
	case a.structure != "":
		return fmt.Sprintf("structure[%s](%s, %v, args, %d)", a.structure, desc, output, i)
	case a.valueRank == 1:
		return fmt.Sprintf("array[%s](%s, %v, args, %d)", a.kind.array, desc, output, i)
	}
	switch a.kind.get {
	case "pointer":
		return fmt.Sprintf("pointer[%s](%s, %v, args, %d)", strings.TrimPrefix(a.kind.goType, "*"), desc, output, i)
	case "variant":
		return fmt.Sprintf("variant(%s, %v, args, %d)", desc, output, i)
	}
	return fmt.Sprintf("scalar[%s](%s, %v, args, %d)", a.kind.goType, desc, output, i)
}

// packer returns the expression that makes the Variant of the field.
func (a *arg) packer() string {
	f := "x." + a.field
	switch {
	case a.structure != "" && a.valueRank == 1:
		return fmt.Sprintf("packStructures(%s)", f)
	case a.structure != "":
		return fmt.Sprintf("ua.MustVariant(ua.NewExtensionObject(%s))", f)
	case a.valueRank == 1 && a.kind.packArray != "":
		return fmt.Sprintf(a.kind.packArray, f)
	case a.valueRank == 1:
		return fmt.Sprintf("ua.MustVariant(%s)", f)
	}
	return fmt.Sprintf(a.kind.pack, f)
}

func (e *emitter) method(f family, t *objectType, m *method) {
	desc := m.goName
	where := t.name
	if m.clause != "" {
		where += " (" + m.clause + ")"
	}
	e.p("")
	e.comment("", wrap(fmt.Sprintf("%s is the contract of the Method %s of %s.", desc, m.name, where), 76))
	e.p("var %s = &Method{", desc)
	e.p("Name: %q, ObjectType: %q, Namespace: %q,", m.name, t.name, f.Namespace)
	e.p("ID: %d, ObjectTypeID: %d,", m.id, t.id)
	e.p("Clause: %q, Mandatory: %v,", m.clause, m.mandatory)
	for _, x := range []struct {
		name string
		args []*arg
	}{{"in", m.in}, {"out", m.out}} {
		if len(x.args) == 0 {
			continue
		}
		e.p("%s: []argument{", x.name)
		for _, a := range x.args {
			typ := a.kind.typeID
			if typ == "" {
				typ = "0"
			}
			e.p("{name: %q, dataType: %d, valueRank: %d, builtin: %s, description: %q},", a.name, a.dataType, a.valueRank, typ, a.description)
		}
		e.p("},")
	}
	e.p("}")

	for _, x := range []struct {
		suffix, prop string
		output       bool
		args         []*arg
	}{{"Input", "InputArguments", false, m.in}, {"Output", "OutputArguments", true, m.out}} {
		if len(x.args) == 0 {
			continue
		}
		name := desc + x.suffix
		e.p("")
		e.comment("", fmt.Sprintf("%s are the %s of %s.%s.", name, x.prop, t.name, m.name))
		e.p("type %s struct {", name)
		for i, a := range x.args {
			if i > 0 {
				e.p("")
			}
			doc := fmt.Sprintf("%s is the argument %s, %s", a.field, a.name, a.dataTypeName)
			if a.valueRank == 1 {
				doc += " array"
			}
			if a.description != "" {
				doc += ": " + strings.TrimSuffix(strings.TrimSpace(a.description), ".") + "."
			} else {
				doc += "."
			}
			e.comment("\t", wrap(doc, 72))
			e.p("%s %s", a.field, a.goType())
		}
		e.p("}")
		e.p("")
		e.comment("", fmt.Sprintf("Pack returns the %s in the order of their declaration.", x.prop))
		e.p("func (x *%s) Pack() []*ua.Variant {", name)
		e.p("return []*ua.Variant{")
		for _, a := range x.args {
			e.p("%s,", a.packer())
		}
		e.p("}")
		e.p("}")
		e.p("")
		e.comment("", fmt.Sprintf(`Unpack sets x from the %s of a call. An error is an
*ArgumentError: Bad_ArgumentsMissing, Bad_TooManyArguments or
Bad_TypeMismatch, as the Call service gives them; x is unchanged then.`, x.prop))
		e.p("func (x *%s) Unpack(args []*ua.Variant) error {", name)
		e.p("if err := %s.count(%v, args); err != nil { return err }", desc, x.output)
		e.p("var y %s", name)
		e.p("var err error")
		for i, a := range x.args {
			e.p("if y.%s, err = %s; err != nil { return err }", a.field, a.getter(desc, x.output, i))
		}
		e.p("*x = y")
		e.p("return nil")
		e.p("}")
	}

	// The client call.
	e.p("")
	e.comment("", wrap(fmt.Sprintf(`Call%s calls %s of the Object obj. method is the
NodeId of the Method: that of the Method of obj, or nil for the
declaration (%s.NodeID(0)), which the server maps to the Method of obj.
A Bad result is a *CallError; outputs that do not match the declaration
are an *ArgumentError.`, desc, m.name, desc), 76))
	params := "ctx context.Context, c Caller, obj, method *ua.NodeID"
	in := "nil"
	if len(m.in) > 0 {
		params += ", in *" + desc + "Input"
		in = "in.Pack()"
	}
	if len(m.out) > 0 {
		e.p("func Call%s(%s) (*%sOutput, error) {", desc, params, desc)
	} else {
		e.p("func Call%s(%s) error {", desc, params)
	}
	if len(m.in) > 0 {
		e.p("if in == nil { in = new(%sInput) }", desc)
	}
	if len(m.out) > 0 {
		e.p("args, err := %s.Call(ctx, c, obj, method, %s)", desc, in)
		e.p("if err != nil { return nil, err }")
		e.p("out := new(%sOutput)", desc)
		e.p("if err := out.Unpack(args); err != nil { return nil, err }")
		e.p("return out, nil")
	} else {
		e.p("args, err := %s.Call(ctx, c, obj, method, %s)", desc, in)
		e.p("if err != nil { return err }")
		e.p("return %s.count(true, args)", desc)
	}
	e.p("}")
}

// wrap breaks s into lines of at most n characters.
func wrap(s string, n int) string {
	var b strings.Builder
	line := 0
	for _, w := range strings.Fields(s) {
		if line > 0 && line+1+len(w) > n {
			b.WriteByte('\n')
			line = 0
		} else if line > 0 {
			b.WriteByte(' ')
			line++
		}
		b.WriteString(w)
		line += len(w)
	}
	return b.String()
}
