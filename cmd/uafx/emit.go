const header = "// SPDX-License-Identifier: MIT\n\n// Code generated by cmd/uafx from the UAFX NodeSets. DO NOT EDIT.\n\n"

var nsConst = map[string]string{"data": "nsData", "ac": "nsAC", "cm": "nsCM"}
var idPkg = map[string]string{"data": "fxdataid", "ac": "fxacid", "cm": "fxcmid"}

type emitter struct {
	m   *model
	buf bytes.Buffer
}

func (e *emitter) p(format string, args ...any) {
	fmt.Fprintf(&e.buf, format, args...)
	e.buf.WriteByte('\n')
}

func (e *emitter) source() ([]byte, error) {
	out, err := format.Source(e.buf.Bytes())
	if err != nil {
		return e.buf.Bytes(), fmt.Errorf("gofmt: %w", err)
	}
	return out, nil
}

// comment writes s as a Go comment.
func (e *emitter) comment(indent, s string) {
	for _, l := range strings.Split(strings.TrimSpace(s), "\n") {
		e.p("%s// %s", indent, l)
	}
}

func clause(t *dataType) string {
	if t.doc == "" {
		return "Part 81"
	}
	return "Part 81 §" + t.doc
}

// fx returns the UAFX DataType of f, nil for one of namespace 0.
func (e *emitter) fx(f *field) *dataType { return e.m.types[f.dt] }

// isEO reports whether f is encoded as an ExtensionObject: its DataType is
// abstract or the field allows subtypes (Part 6 §5.2.6).
func (e *emitter) isEO(f *field) bool {
	if t := e.fx(f); t != nil {
		return (t.kind == kStruct || t.kind == kUnion) && (t.abstract || f.allowSub)
	}
	return builtins[f.dt.id].wire == wEO
}

// eoType returns the Go type of an ExtensionObject field of a UAFX
// DataType: the configured subtype or the interface of the DataType.
func (e *emitter) eoType(f *field) (string, bool) {
	if f.cfg.Concrete != "" {
		t := e.m.byName[e.fx(f).ns+":"+f.cfg.Concrete]
		return "*" + t.goName, true
	}
	t := e.fx(f)
	if t.abstract {
		return t.goName, false
	}
	return "*" + t.goName, true
}

// elemType is the Go type of one value of f.
func (e *emitter) elemType(f *field) string {
	t := e.fx(f)
	if t == nil {
		return builtins[f.dt.id].goType
	}
	switch {
	case t.kind == kEnum || t.kind == kOptionSet:
		return t.goName
	case e.isEO(f):
		s, _ := e.eoType(f)
		return s
	}
	return "*" + t.goName
}

// bufferName is the name ua.Buffer gives an unsigned integer type.
var bufferName = map[string]string{"uint8": "Uint8", "uint16": "Uint16", "uint32": "Uint32"}

// goType is the Go type of f; a scalar of an optional field or a union
// option is a pointer when its type cannot be nil.
func (e *emitter) goType(f *field, nullable bool) string {
	s := e.elemType(f)
	if f.array {
		return "[]" + s
	}
	if nullable && !e.canBeNil(f) {
		return "*" + s
	}
	return s
}

func (e *emitter) canBeNil(f *field) bool {
	if f.array {
		return true
	}
	if t := e.fx(f); t != nil {
		if t.kind == kEnum || t.kind == kOptionSet {
			return false
		}
		return true // a pointer or an interface
	}
	g := builtins[f.dt.id].goType
	return strings.HasPrefix(g, "*") || strings.HasPrefix(g, "[]")
}

func fieldName(f *field) string { return goname.Format(f.name) }

// --- types --------------------------------------------------------------------

func (e *emitter) types() {
	e.p("%spackage uafx\n", header)
	e.p("import (\n\"strconv\"\n\n\"github.com/otfabric/go-opcua/ua\"\n)\n")
	for _, t := range e.m.order {
		switch t.kind {
		case kEnum, kOptionSet:
			e.enum(t)
		case kStruct, kUnion:
			if t.abstract {
				e.iface(t)
			} else {
				e.structType(t)
			}
		}
	}
}

func (e *emitter) enum(t *dataType) {
	what := "enumeration"
	under := "int32"
	if t.kind == kOptionSet {
		what = "OptionSet"
		under = optionSetBases[t.base.id]
	}
	if t.cfg.Doc != "" {
		e.comment("", t.cfg.Doc)
	} else {
		e.p("// %s is the %s %s of %s.", t.goName, t.name, what, clause(t))
	}
	e.p("type %s %s\n", t.goName, under)
	pre := t.goName
	if t.cfg.Prefix != nil {
		pre = *t.cfg.Prefix
	}
	if t.kind == kOptionSet {
		e.p("// The bits of %s (%s).", t.name, clause(t))
	} else {
		e.p("// The values of %s (%s).", t.name, clause(t))
	}
	e.p("const (")
	for _, v := range t.values {
		if t.kind == kOptionSet {
			e.p("%s%s %s = 1 << %d", pre, goname.Format(v.name), t.goName, v.v)
		} else {
			e.p("%s%s %s = %d", pre, goname.Format(v.name), t.goName, v.v)
		}
	}
	e.p(")\n")
	if t.cfg.NoString {
		return
	}
	if t.kind == kOptionSet {
		low := strings.ToLower(t.goName[:1]) + t.goName[1:] + "Names"
		e.p("var %s = []bitName{", low)
		for _, v := range t.values {
			e.p("{%d, %q},", v.v, v.name)
		}
		e.p("}\n")
		e.p("// String returns the names of the bits that are set, separated by \"|\",\n// or \"OK\" when none is.")
		e.p("func (v %s) String() string { return bitString(uint64(v), %s) }\n", t.goName, low)
		return
	}
	e.p("// String returns the name of the value, or its number if it has none.")
	e.p("func (v %s) String() string {\nswitch v {", t.goName)
	for _, v := range t.values {
		e.p("case %s%s: return %q", pre, goname.Format(v.name), v.name)
	}
	e.p("}\nreturn %q + strconv.FormatInt(int64(v), 10) + \")\"\n}\n", t.goName+"(")
}

func (e *emitter) iface(t *dataType) {
	var names []string
	for _, c := range t.concrete() {
		names = append(names, "*"+c.goName)
	}
	e.p("// %s is a value of the abstract %s of %s: %s.", t.goName, t.name, clause(t), strings.Join(names, ", "))
	e.p("type %s interface {\nStructure\nis%s()\n}\n", t.goName, t.goName)
}

func (e *emitter) structType(t *dataType) {
	if t.cfg.Doc != "" {
		e.comment("", t.cfg.Doc)
	} else {
		what := t.name
		switch {
		case t.kind == kUnion:
			e.p("// %s is the %s union of %s. At most one field is set; none is the\n// null union.", t.goName, t.name, clause(t))
		case t.optBits > 0:
			e.p("// %s is the %s of %s. A nil optional field is absent.", t.goName, what, clause(t))
		default:
			e.p("// %s is the %s of %s.", t.goName, what, clause(t))
		}
	}
	e.p("type %s struct {", t.goName)
	for _, f := range t.fields() {
		if f.cfg.Doc != "" {
			e.comment("\t", f.cfg.Doc)
		} else if f.optional {
			e.p("\t// %s is optional.", fieldName(f))
		}
		e.p("%s %s", fieldName(f), e.goType(f, f.optional || t.kind == kUnion))
	}
	e.p("}\n")
	for s := t.super; s != nil; s = s.super {
		if s.abstract {
			e.p("func (*%s) is%s() {}", t.goName, s.goName)
		}
	}
	e.p("")
}

// --- codec --------------------------------------------------------------------

func (e *emitter) codec() {
	e.p("%spackage uafx\n", header)
	e.p("import (\n\"github.com/otfabric/go-opcua/ua\"\n\"github.com/otfabric/go-opcua/uafx/fxacid\"\n\"github.com/otfabric/go-opcua/uafx/fxcmid\"\n\"github.com/otfabric/go-opcua/uafx/fxdataid\"\n)\n")
	e.p("// structures makes a value of each structure by its Default Binary\n// encoding.")
	e.p("var structures = map[encodingID]func() Structure{")
	for _, t := range e.m.order {
		if (t.kind == kStruct || t.kind == kUnion) && !t.abstract {
			e.p("{%s, %s}: func() Structure { return new(%s) },", nsConst[t.ns], e.encName(t), t.goName)
		}
	}
	e.p("}\n")
	for _, t := range e.m.order {
		if (t.kind == kStruct || t.kind == kUnion) && !t.abstract {
			e.p("func (*%s) encodingID() encodingID { return encodingID{%s, %s} }\n", t.goName, nsConst[t.ns], e.encName(t))
			if t.kind == kUnion {
				e.unionCodec(t)
			} else {
				e.structCodec(t)
			}
		}
	}
}

func (e *emitter) encName(t *dataType) string {
	return idPkg[t.ns] + "." + goname.Format(t.name+"_Encoding_DefaultBinary")
}

func (e *emitter) structCodec(t *dataType) {
	fs := t.fields()
	e.p("func (v *%s) encode(w *wbuf) {", t.goName)
	if t.optBits > 0 {
		e.p("var mask uint32")
		bit := 0
		for _, f := range fs {
			if f.optional {
				e.p("if v.%s != nil { mask |= 1 << %d }", fieldName(f), bit)
				bit++
			}
		}
		e.p("w.WriteUint32(mask)")
	}
	for _, f := range fs {
		x := "v." + fieldName(f)
		if f.optional {
			e.p("if %s != nil {", x)
			e.encodeValue(f, x, !e.canBeNil(f))
			e.p("}")
			continue
		}
		e.encodeValue(f, x, false)
	}
	e.p("}\n")

	e.p("func (v *%s) decode(r *rbuf) {", t.goName)
	if t.optBits > 0 {
		e.p("mask := r.ReadUint32()")
		e.p("if mask>>%d != 0 { r.fail(%q, mask) }", t.optBits, t.name+": reserved bits of the EncodingMask are set: %#x")
		bit := 0
		for _, f := range fs {
			x := "v." + fieldName(f)
			if f.optional {
				e.p("if mask&(1<<%d) != 0 {", bit)
				e.decodeValue(t, f, x, !e.canBeNil(f), false)
				e.p("}")
				bit++
				continue
			}
			e.decodeValue(t, f, x, false, false)
		}
	} else {
		for _, f := range fs {
			e.decodeValue(t, f, "v."+fieldName(f), false, false)
		}
	}
	e.p("}\n")
}

func (e *emitter) unionCodec(t *dataType) {
	fs := t.fields()
	e.p("func (v *%s) encode(w *wbuf) {", t.goName)
	e.p("var sw uint32")
	for i, f := range fs {
		e.p("if v.%s != nil { if sw != 0 { w.fail(%q); return }; sw = %d }", fieldName(f), t.name+": more than one field is set", i+1)
	}
	e.p("w.WriteUint32(sw)\nswitch sw {")
	for i, f := range fs {
		e.p("case %d:", i+1)
		e.encodeValue(f, "v."+fieldName(f), !e.canBeNil(f))
	}
	e.p("}\n}\n")

	e.p("func (v *%s) decode(r *rbuf) {", t.goName)
	e.p("switch sw := r.ReadUint32(); sw {\ncase 0:")
	for i, f := range fs {
		e.p("case %d:", i+1)
		e.decodeValue(t, f, "v."+fieldName(f), !e.canBeNil(f), true)
	}
	e.p("default:\nif r.Error() == nil { r.fail(%q, sw) }", t.name+": SwitchField %d")
	e.p("}\n}\n")
	e.p("func (v *%s) isNull() bool { return %s }\n", t.goName, e.allNil(fs))
}

func (e *emitter) allNil(fs []*field) string {
	var parts []string
	for _, f := range fs {
		parts = append(parts, "v."+fieldName(f)+" == nil")
	}
	return strings.Join(parts, " && ")
}

// encodeValue writes the encoding of x, the value of f; deref when x is a
// pointer to the value.
func (e *emitter) encodeValue(f *field, x string, deref bool) {
	if f.array {
		e.encodeArray(f, x)
		return
	}
	if deref {
		x = "*" + x
	}
	e.encodeScalar(f, x)
}

func (e *emitter) encodeScalar(f *field, x string) {
	t := e.fx(f)
	switch {
	case t == nil:
		switch builtins[f.dt.id].wire {
		case wBool:
			e.p("w.WriteBool(%s)", x)
		case wUint8:
			e.p("w.WriteUint8(%s)", x)
		case wUint16:
			e.p("w.WriteUint16(%s)", x)
		case wInt32:
			e.p("w.WriteInt32(%s)", x)
		case wUint32:
			e.p("w.WriteUint32(%s)", x)
		case wFloat64:
			e.p("w.WriteFloat64(%s)", x)
		case wString:
			e.p("w.WriteString(%s)", x)
		default:
			e.p("w.WriteStruct(%s)", x)
		}
	case t.kind == kEnum:
		e.p("w.WriteInt32(int32(%s))", x)
	case t.kind == kOptionSet:
		e.p("w.Write%s(%s(%s))", bufferName[optionSetBases[t.base.id]], optionSetBases[t.base.id], x)
	case e.isEO(f):
		e.p("w.extensionObject(%s)", x)
	case t.kind == kUnion:
		e.p("if %s == nil { w.WriteUint32(0) } else { %s.encode(w) }", x, x)
	default:
		e.p("if %s == nil { (&%s{}).encode(w) } else { %s.encode(w) }", x, t.goName, x)
	}
}

func (e *emitter) encodeArray(f *field, x string) {
	t := e.fx(f)
	if t == nil && builtins[f.dt.id].wire != wEO {
		e.p("w.WriteStruct(%s)", x)
		return
	}
	if t == nil { // an array of ExtensionObjects of namespace 0
		e.p("w.WriteStruct(%s)", x)
		return
	}
	e.p("if w.length(len(%s), %s == nil) {\nfor _, x := range %s {", x, x, x)
	e.encodeScalar(&field{dt: f.dt, allowSub: f.allowSub, cfg: f.cfg}, "x")
	e.p("}\n}")
}

// decodeValue reads the value of f into x; alloc when x is a pointer to the
// value; option when f is the selected field of a union.
func (e *emitter) decodeValue(owner *dataType, f *field, x string, alloc, option bool) {
	if f.array {
		e.decodeArray(owner, f, x)
		return
	}
	if alloc {
		e.p("%s = new(%s)", x, e.elemType(f))
		x = "*" + x
	}
	e.decodeScalar(owner, f, x, option)
}

func (e *emitter) decodeScalar(owner *dataType, f *field, x string, option bool) {
	t := e.fx(f)
	switch {
	case t == nil:
		b := builtins[f.dt.id]
		switch b.wire {
		case wBool:
			e.p("%s = r.ReadBool()", x)
		case wUint8:
			e.p("%s = r.ReadUint8()", x)
		case wUint16:
			e.p("%s = r.ReadUint16()", x)
		case wInt32:
			e.p("%s = r.ReadInt32()", x)
		case wUint32:
			e.p("%s = r.ReadUint32()", x)
		case wFloat64:
			e.p("%s = r.ReadFloat64()", x)
		case wString:
			e.p("%s = r.ReadString()", x)
		case wPtr, wEO:
			e.p("%s = new(%s)\nr.ReadStruct(%s)", x, strings.TrimPrefix(b.goType, "*"), x)
		default:
			e.p("r.ReadStruct(&%s)", x)
		}
	case t.kind == kEnum:
		e.p("%s = %s(r.ReadInt32())", x, t.goName)
	case t.kind == kOptionSet:
		e.p("%s = %s(r.Read%s())", x, t.goName, bufferName[optionSetBases[t.base.id]])
	case e.isEO(f):
		goT, _ := e.eoType(f)
		e.p("if s := r.extensionObject(func(s Structure) bool { _, ok := s.(%s); return ok }); s != nil { %s = s.(%s) }", goT, x, goT)
		if option {
			e.p("if %s == nil && r.Error() == nil { r.fail(%q) }", x, owner.name+"."+f.name+": a null ExtensionObject")
		}
	case t.kind == kUnion:
		e.p("{\nu := new(%s)\nu.decode(r)\nif !u.isNull() { %s = u }\n}", t.goName, x)
	default:
		e.p("%s = new(%s)\n%s.decode(r)", x, t.goName, x)
	}
}

func (e *emitter) decodeArray(owner *dataType, f *field, x string) {
	t := e.fx(f)
	if t == nil {
		e.p("r.ReadStruct(&%s)", x)
		return
	}
	e.p("if n, ok := r.length(); ok {\n%s = make(%s, n)\nfor i := range %s {", x, e.goType(f, false), x)
	e.decodeScalar(owner, &field{name: f.name, dt: f.dt, allowSub: f.allowSub, cfg: f.cfg}, x+"[i]", false)
	e.p("if r.Error() != nil { return }\n}\n}")
}

// --- schema metadata for the tests ---------------------------------------------

// schema writes what the tests compare with the Binary Schemas (BSD) of the
// UAFX NodeSets, which the generator does not read: the fields of each
// structure in the order of its encoding.
func (e *emitter) schema() {
	e.p("%spackage uafx\n", header)
	e.p("import (\n\"github.com/otfabric/go-opcua/uafx/fxacid\"\n\"github.com/otfabric/go-opcua/uafx/fxcmid\"\n\"github.com/otfabric/go-opcua/uafx/fxdataid\"\n)\n")
	e.p("var generatedSchema = []schemaType{")
	for _, t := range e.m.order {
		if t.kind == kEnum || t.kind == kOptionSet {
			e.p("{ns: %q, name: %q, enum: true, values: %d},", t.ns, t.name, len(t.values))
			continue
		}
		enc := "0"
		if !t.abstract {
			enc = e.encName(t)
		}
		e.p("{ns: %q, name: %q, union: %v, abstract: %v, binary: %d, encodingConst: %s, value: %s, fields: []schemaField{", t.ns, t.name, t.kind == kUnion, t.abstract, t.binary, enc, e.sample(t))
		for _, f := range t.fields() {
			typ := ""
			if ft := e.fx(f); ft != nil {
				typ = ft.name
			} else {
				typ = builtins[f.dt.id].name
			}
			e.p("{name: %q, dataType: %q, array: %v, optional: %v, eo: %v},", f.name, typ, f.array, f.optional, e.isEO(f))
		}
		e.p("}},")
	}
	e.p("}")
}

func (e *emitter) sample(t *dataType) string {
	if t.abstract {
		return "nil"
	}
	return "new(" + t.goName + ")"
}
